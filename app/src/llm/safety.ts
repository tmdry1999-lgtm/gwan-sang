const BANNED = [
  '수명', '단명', '요절', '사망', '죽음', '죽는', '질병', '병에', '암에', '사고를', '사고가', '이혼', '불행', '저주', '망한', '망할', '가난',
  '못생', '뚱뚱', '비만', '추하', '흉측', '비대칭', '피부가',
  '반드시', '무조건', '틀림없이',
  '오락용',
  '여자는', '남자는', '여자라서', '남자라서',
  '공부를 못', '머리가 나쁘',
];

export function isSafe(text: string): boolean {
  return !BANNED.some((w) => text.includes(w));
}
